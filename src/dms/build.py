"""`dms build <map>`: map source -> maps/<map>/TEXTMAP -> build/<map>/<map>.wad.

Generated maps: map.py's build(m) runs, and its output is written to TEXTMAP with a header line
holding a hash of the content. If TEXTMAP no longer matches its hash, someone edited it by hand,
and build refuses to overwrite it. Hand-edited maps: TEXTMAP is the source and is only packed.
The WAD holds MAPINFO (title, sky, music, no jumping or crouching) and the map in slot MAP01.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import re
from pathlib import Path

from dataclasses import dataclass

from dms import udmf, wad
from dms.catalog import load as load_catalog
from dms.gen import MapBuilder
from dms.maps import MapError, MapInfo
from dms.validate import Issue, report, validate

HEADER_RE = re.compile(r"^// generated by dms from map\.py; content sha256 ([0-9a-f]{64})\n")


class BuildError(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate(info: MapInfo) -> str:
    """Run the map's map.py and return the TEXTMAP text (with the hash header)."""
    spec = importlib.util.spec_from_file_location(f"dms_map_{info.name.replace('-', '_')}", info.generator)
    if spec is None or spec.loader is None:
        raise BuildError(f"can't load {info.generator}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if not hasattr(module, "build"):
        raise BuildError(f"{info.generator} has no build(m) function")
    m = MapBuilder()
    module.build(m)
    body = udmf.dump(m.textmap())
    return f"// generated by dms from map.py; content sha256 {sha256(body.encode('utf-8'))}\n" + body


def hand_edited_since_generated(text: str) -> bool:
    """True if a generated TEXTMAP was changed after dms wrote it (or isn't dms output at all)."""
    m = HEADER_RE.match(text)
    if not m:
        return True
    return sha256(text[m.end():].encode("utf-8")) != m.group(1)


def mapinfo(info: MapInfo) -> str:
    lines = [
        "// Written by dms build.",
        "defaultmap",
        "{",
        "\tnojump",
        "\tnocrouch",
        "}",
        "",
        f'map MAP01 "{info.title}"',
        "{",
        f'\tsky1 = "{info.sky}"',
    ]
    if info.music:
        lines.append(f'\tmusic = "{info.music}"')
    lines += ["}", ""]
    return "\n".join(lines)


def map_lumps(info: MapInfo, textmap: bytes) -> list[wad.Lump]:
    return [
        wad.Lump("MAPINFO", mapinfo(info).encode("utf-8")),
        wad.Lump("MAP01"),
        wad.Lump("TEXTMAP", textmap),
        wad.Lump("ENDMAP"),
    ]


# ---------------------------------------------------------------- edit.wad bookkeeping

def _edit_state_path(info: MapInfo, root: Path) -> Path:
    return info.build_dir(root) / "edit.state.json"


def edit_wad_changed(info: MapInfo, root: Path) -> bool:
    """True if the mapper saved edit.wad in the editor since dms last packed it."""
    ew = info.edit_wad(root)
    state = _edit_state_path(info, root)
    if not ew.exists():
        return False
    if not state.exists():
        return True
    packed = json.loads(state.read_text(encoding="utf-8")).get("sha256")
    return packed != sha256(ew.read_bytes())


def pack_edit_wad(info: MapInfo, root: Path) -> Path:
    ew = info.edit_wad(root)
    wad.write(ew, map_lumps(info, info.textmap.read_bytes()))
    _edit_state_path(info, root).write_text(json.dumps({"sha256": sha256(ew.read_bytes())}) + "\n", encoding="utf-8")
    return ew


# ---------------------------------------------------------------- build

@dataclass
class BuildResult:
    wad: Path
    issues: list[Issue]

    @property
    def errors(self) -> int:
        return sum(1 for i in self.issues if i.severity == "error")


def check(tm: udmf.Textmap, root: Path, title: str, report_path: Path | None) -> list[Issue]:
    """Validate a textmap against the catalog, print the result, and write it to report_path."""
    cat = load_catalog(root)
    issues = validate(tm, cat)
    if cat is None:
        issues.append(Issue("warning", "no texture catalog yet, textures not checked (run `dms catalog`)"))
    text = report(issues, title)
    print("    " + text.rstrip().replace("\n", "\n    "))
    if report_path is not None:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(text, encoding="utf-8", newline="\n")
    return issues


def build(info: MapInfo, root: Path, force: bool = False) -> BuildResult:
    """Generate (if needed), validate and pack. The WAD is written even when validation finds
    errors, so the map can still be opened to look at the problem; the result carries them."""
    print(f"dms build: {info.name} ({info.source})")
    if edit_wad_changed(info, root) and not force:
        raise BuildError(
            f"{info.edit_wad(root)} has editor changes that aren't in the map's source yet.\n"
            "    Bringing them back (`dms pull`) isn't built yet; ask Claude. To discard them, build with --force."
        )

    if info.source == "generated":
        if not info.generator.exists():
            raise BuildError(f"{info.generator} is missing (source = \"generated\")")
        if info.textmap.exists() and not force:
            current = info.textmap.read_text(encoding="utf-8")
            if hand_edited_since_generated(current):
                raise BuildError(
                    f"{info.textmap} was edited by hand since it was generated; building would overwrite it.\n"
                    "    Either move those edits into map.py, switch the map to source = \"hand-edited\", "
                    "or build with --force to discard them."
                )
        text = generate(info)
        info.textmap.write_text(text, encoding="utf-8", newline="\n")
        print(f"    wrote {info.textmap}")
    elif not info.textmap.exists():
        raise BuildError(f"{info.textmap} is missing (source = \"hand-edited\")")

    data = info.textmap.read_bytes()
    try:
        tm = udmf.parse(data.decode("utf-8"))
    except (UnicodeDecodeError, udmf.UdmfError) as e:
        raise BuildError(f"{info.textmap}: {e}") from None

    plural = {"vertex": "vertices"}
    counts = ", ".join(f"{len(tm.of(k))} {plural.get(k, k + 's')}" for k in udmf.KINDS)
    print(f"    {counts}")
    issues = check(tm, root, "validate", info.build_dir(root) / "validate.txt")

    out = info.wad(root)
    previous = _packed_textmap(out)
    wad.write(out, map_lumps(info, data))
    print(f"    wrote {out}")
    draw(info, root, tm, issues, previous)
    return BuildResult(out, issues)


def _packed_textmap(path: Path) -> udmf.Textmap | None:
    """The TEXTMAP inside an existing WAD (the previous build), or None."""
    if not path.exists():
        return None
    try:
        _, lumps = wad.read(path)
        i = wad.find(lumps, "TEXTMAP")
        return udmf.parse(lumps[i].data.decode("utf-8")) if i >= 0 else None
    except (wad.WadError, udmf.UdmfError, UnicodeDecodeError):
        return None


def draw(info: MapInfo, root: Path, tm: udmf.Textmap, issues: list[Issue], previous: udmf.Textmap | None,
         suffix: str = "", diff_title: str = "") -> None:
    """render<suffix>.png/.txt, and diff<suffix>.png/.txt against `previous` when given."""
    from dms import render

    d = info.build_dir(root)
    png = render.render(tm, d / f"render{suffix}.png", issues, title=f"{info.name}{suffix}")
    print(f"    wrote {png} (+ {png.with_suffix('.txt').name})")
    if previous is not None:
        diff_png = d / f"diff{suffix}.png"
        if render.render_diff(previous, tm, diff_png, title=diff_title or f"{info.name}{suffix}"):
            print(f"    wrote {diff_png} (+ {diff_png.with_suffix('.txt').name})")
        else:
            print("    no changes since the previous build")


def needs_build(info: MapInfo, root: Path) -> bool:
    out = info.wad(root)
    if not out.exists():
        return True
    sources = [info.folder / "map.toml", info.textmap, info.generator]
    newest = max((p.stat().st_mtime for p in sources if p.exists()), default=0)
    return newest > out.stat().st_mtime


def read_edit_wad_textmap(info: MapInfo, root: Path) -> udmf.Textmap:
    """The map as the mapper last saved it in the editor (build/<map>/edit.wad)."""
    ew = info.edit_wad(root)
    if not ew.exists():
        raise BuildError(f"{ew} doesn't exist (open the map with `dms edit` first)")
    _, lumps = wad.read(ew)
    i = wad.find(lumps, "TEXTMAP")
    if i < 0:
        raise BuildError(f"{ew} has no TEXTMAP")
    return udmf.parse(lumps[i].data.decode("utf-8"))


