"""`dms build <map>`: map source -> maps/<map>/TEXTMAP -> build/<map>/<map>.wad.

Generated maps: map.py's build(m) runs, and its output is written to TEXTMAP with a header line
holding a hash of the content. If TEXTMAP no longer matches its hash, someone edited it by hand,
and build refuses to overwrite it. Hand-edited maps: TEXTMAP is the source and is only packed.
The WAD holds MAPINFO (title, sky, music, no jumping or crouching) and the map in slot MAP01.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import re
import tomllib
from pathlib import Path

from dataclasses import dataclass

from dms import udmf, wad
from dms.catalog import load as load_catalog
from dms.gen import MapBuilder
from dms.maps import MapError, MapInfo
from dms.validate import Issue, report, validate

HEADER_RE = re.compile(r"^// generated by dms from map\.py; content sha256 ([0-9a-f]{64})\n")


class BuildError(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate(info: MapInfo) -> str:
    """Run the map's map.py and return the TEXTMAP text (with the hash header)."""
    spec = importlib.util.spec_from_file_location(f"dms_map_{info.name.replace('-', '_')}", info.generator)
    if spec is None or spec.loader is None:
        raise BuildError(f"can't load {info.generator}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if not hasattr(module, "build"):
        raise BuildError(f"{info.generator} has no build(m) function")
    m = MapBuilder()
    module.build(m)
    tm = m.textmap()
    from dms import overrides

    try:
        data = overrides.load(info)
    except (ValueError, tomllib.TOMLDecodeError) as e:
        raise BuildError(f"{overrides.path(info)}: {e}") from None
    if data:
        n = sum(len(t) for t in data.values())
        print(f"    applied {overrides.FILENAME} ({n} element(s) tweaked in the editor)")
        for w in overrides.apply(tm, data):
            print(f"    warning: {w}")
    body = udmf.dump(tm)
    return f"// generated by dms from map.py; content sha256 {sha256(body.encode('utf-8'))}\n" + body


def hand_edited_since_generated(text: str) -> bool:
    """True if a generated TEXTMAP was changed after dms wrote it (or isn't dms output at all)."""
    m = HEADER_RE.match(text)
    if not m:
        return True
    return sha256(text[m.end():].encode("utf-8")) != m.group(1)


def mapinfo(info: MapInfo, handlers: list[str] | tuple = ()) -> str:
    """handlers: the map's own ZScript event handlers (scripts.py), registered for this map only."""
    lines = [
        "// Written by dms build.",
        "defaultmap",
        "{",
        "\tnojump",
        "\tnocrouch",
        "}",
        "",
        f'map MAP01 "{info.title}"',
        "{",
        f'\tsky1 = "{info.sky}"',
    ]
    if info.music:
        lines.append(f'\tmusic = "{info.music}"')
    if handlers:
        lines.append("\tEventHandlers = " + ", ".join(f'"{h}"' for h in handlers))
    lines += ["}", ""]
    return "\n".join(lines)


def map_lumps(info: MapInfo, textmap: bytes, zscript: bytes | None = None) -> list[wad.Lump]:
    """The map's WAD. zscript: its per-map script (scripts.py), for the game's WAD; edit.wad goes
    without (the editor doesn't run it)."""
    from dms import extras, scripts

    lumps = [wad.Lump("MAPINFO", mapinfo(info, scripts.handlers(zscript)).encode("utf-8"))]
    lumps += extras.lumps(info)   # the map's own textures (TEXTURES, ANIMDEFS): the editor shows them too
    if zscript:
        lumps.append(wad.Lump("ZSCRIPT", zscript))
    return lumps + [wad.Lump("MAP01"), wad.Lump("TEXTMAP", textmap), wad.Lump("ENDMAP")]


# ---------------------------------------------------------------- edit.wad bookkeeping

def _edit_state_path(info: MapInfo, root: Path) -> Path:
    return info.build_dir(root) / "edit.state.json"


def edit_wad_changed(info: MapInfo, root: Path) -> bool:
    """True if the mapper saved changes to the map in edit.wad since dms last packed it.
    A save that only rewrote the file (same map data, plus the editor's nodes) doesn't count."""
    ew = info.edit_wad(root)
    state = _edit_state_path(info, root)
    if not ew.exists():
        return False
    if state.exists() and json.loads(state.read_text(encoding="utf-8")).get("sha256") == sha256(ew.read_bytes()):
        return False
    if not info.textmap.exists():
        return True
    try:
        saved = read_edit_wad_textmap(info, root)
        return not udmf.same(saved, udmf.parse(info.textmap.read_text(encoding="utf-8")))
    except (BuildError, wad.WadError, udmf.UdmfError, UnicodeDecodeError):
        return True


def editor_state(info: MapInfo, root: Path) -> dict:
    """What the editor plugin last reported for this map: {"open": bool, "unsaved_changes": bool, ...}."""
    p = info.build_dir(root) / "editor-state.json"
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def pack_edit_wad(info: MapInfo, root: Path) -> Path:
    ew = info.edit_wad(root)
    wad.write(ew, map_lumps(info, info.textmap.read_bytes()))
    _edit_state_path(info, root).write_text(json.dumps({"sha256": sha256(ew.read_bytes())}) + "\n", encoding="utf-8")
    return ew


# ---------------------------------------------------------------- build

@dataclass
class BuildResult:
    wad: Path
    issues: list[Issue]

    @property
    def errors(self) -> int:
        return sum(1 for i in self.issues if i.severity == "error")


def check(tm: udmf.Textmap, root: Path, title: str, report_path: Path | None,
          info: MapInfo | None = None) -> list[Issue]:
    """Validate a textmap against the catalog (and, given `info`, the map's own textures: extras.py),
    print the result, and write it to report_path."""
    cat = load_catalog(root)
    if cat is not None and info is not None:
        from dataclasses import replace

        from dms import extras

        walls, flats = extras.textures(info)
        if walls or flats:
            cat = replace(cat, textures={**cat.textures, **walls}, flats=cat.flats | flats)
    issues = validate(tm, cat)
    if cat is None:
        issues.append(Issue("warning", "no texture catalog yet, textures not checked (run `dms catalog`)"))
    text = report(issues, title)
    print("    " + text.rstrip().replace("\n", "\n    "))
    if report_path is not None:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(text, encoding="utf-8", newline="\n")
    return issues


def check_movement(tm: udmf.Textmap, report_path: Path | None = None):
    """Run the movement check, print its summary and write the report to report_path."""
    from dms import movement

    res = movement.check(tm)
    head, *rest = res.report.rstrip().split("\n")
    print(f"    {head}")
    for line in rest:
        if line.startswith("problems") or line.startswith("  warning"):
            print(f"    {line}")
    if report_path is not None:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(res.report, encoding="utf-8", newline="\n")
    return res


def build(info: MapInfo, root: Path, force: bool = False, note: str | None = None) -> BuildResult:
    """Generate (if needed), validate and pack. The WAD is written even when validation finds
    errors, so the map can still be opened to look at the problem; the result carries them.
    A build that changed the map (or carries `note`, Claude's word on it) is added to the
    board's history (build/<map>/history/)."""
    print(f"dms build: {info.name} ({info.source})")
    if edit_wad_changed(info, root) and not force:
        raise BuildError(
            f"{info.edit_wad(root)} has editor changes that aren't in the map's source yet.\n"
            "    Bring them back first: `launchers\\Pull Map.cmd` (or `dms pull` + map name). To discard them, build with --force."
        )

    if info.source == "generated":
        if not info.generator.exists():
            raise BuildError(f"{info.generator} is missing (source = \"generated\")")
        if info.textmap.exists() and not force:
            current = info.textmap.read_text(encoding="utf-8")
            if hand_edited_since_generated(current):
                raise BuildError(
                    f"{info.textmap} was edited by hand since it was generated; building would overwrite it.\n"
                    "    Either move those edits into map.py, switch the map to source = \"hand-edited\", "
                    "or build with --force to discard them."
                )
        text = generate(info)
        info.textmap.write_text(text, encoding="utf-8", newline="\n")
        print(f"    wrote {info.textmap}")
    elif not info.textmap.exists():
        raise BuildError(f"{info.textmap} is missing (source = \"hand-edited\")")

    data = info.textmap.read_bytes()
    try:
        tm = udmf.parse(data.decode("utf-8"))
    except (UnicodeDecodeError, udmf.UdmfError) as e:
        raise BuildError(f"{info.textmap}: {e}") from None

    plural = {"vertex": "vertices"}
    counts = {plural.get(k, k + "s"): len(tm.of(k)) for k in udmf.KINDS}
    print("    " + ", ".join(f"{n} {k}" for k, n in counts.items()))
    issues = check(tm, root, "validate", info.build_dir(root) / "validate.txt", info)
    moves = check_movement(tm, info.build_dir(root) / "movement.txt")
    issues = issues + moves.issues

    from dms import scripts

    out = info.wad(root)
    previous = _packed_textmap(out)
    code = scripts.read(info)
    wad.write(out, map_lumps(info, data, code))
    print(f"    wrote {out}")
    if code:
        names = scripts.handlers(code)
        errors = scripts.check(info, root, out, code)
        if errors is None:
            print(f"    zscript.zs ({', '.join(names) or 'no event handlers'}): not checked (UZDoom isn't set up)")
        else:
            print(f"    zscript.zs ({', '.join(names) or 'no event handlers'}): "
                  + (f"{len(errors)} error(s)" if errors else "compiles"))
            for e in errors:
                print(f"      error: {e}")
            issues = issues + [Issue("error", e, "zscript.zs") for e in errors]
    script_broken = bool(code) and any(i.where == "zscript.zs" for i in issues)
    changed = draw(info, root, tm, issues, previous, moves=moves)
    from dms import history, render

    def view(v) -> dict:  # how map coordinates became pixels, so the board can map a click back
        return {"minx": v.minx, "maxy": v.maxy, "scale": v.scale, "width": v.width, "height": v.height}

    views = {"render.png": view(render.view_for(tm))}
    if previous is not None and changed:
        dv = view(render.view_for(previous, tm))
        views.update({f: dv for f in ("diff.png", "diff-before.png", "diff-after.png")})
    if history.record(info, root, changed=changed, counts=counts, issues=issues, note=note, forced=force,
                      views=views):
        print("    added to the board's history" + (" (with a note)" if note else ""))
    _refresh_edit_wad(info, root, force)
    if script_broken:  # a restart would stop on UZDoom's error window: the running game keeps its build
        print("    the running game keeps its current build until zscript.zs compiles")
    else:
        _refresh_play_wad(info, root, data)
    return BuildResult(out, issues)


def _refresh_play_wad(info: MapInfo, root: Path, textmap: bytes) -> None:
    """While the game runs, write the new build into its live play.wad (live.py): key H in the game
    then reloads the map in place with it."""
    from dms import history, live

    if not live.game_running(info, root):
        return
    from dms import scripts

    latest = history.latest(info, root)
    seq = latest["seq"] if latest else 0
    code = scripts.read(info)
    from dms import extras

    result = live.update_map(info, root, mapinfo(info, scripts.handlers(code)).encode("utf-8"), textmap, seq,
                             zscript=code or b"", extra=extras.lumps(info))
    if result == "updated":
        print(f"    updated the running game's play.wad (build #{seq}): press H in the game to reload in place")
    elif result == "restart":
        print("    the running game can't take this build in place (the map outgrew its slot, or zscript.zs"
              " or the map's textures changed): H in the game will restart it (needs the board)")


def _refresh_edit_wad(info: MapInfo, root: Path, force: bool = False) -> None:
    """Keep edit.wad in step with the new build so an open editor reloads it (via the dms bridge
    plugin). Only when the mapper has no saved edits in it (build refuses earlier otherwise),
    or with --force, which discards them."""
    if not info.edit_wad(root).exists() or (edit_wad_changed(info, root) and not force):
        return
    pack_edit_wad(info, root)
    state = editor_state(info, root)
    if state.get("open") and state.get("unsaved_changes"):
        print("    updated edit.wad; the editor has unsaved changes, so it won't reload until they're saved or undone")
    elif state.get("open"):
        print("    updated edit.wad; the open editor reloads it")
    else:
        print("    updated edit.wad")


def _packed_textmap(path: Path) -> udmf.Textmap | None:
    """The TEXTMAP inside an existing WAD (the previous build), or None."""
    if not path.exists():
        return None
    try:
        _, lumps = wad.read(path)
        i = wad.find(lumps, "TEXTMAP")
        return udmf.parse(lumps[i].data.decode("utf-8")) if i >= 0 else None
    except (wad.WadError, udmf.UdmfError, UnicodeDecodeError):
        return None


def draw(info: MapInfo, root: Path, tm: udmf.Textmap, issues: list[Issue], previous: udmf.Textmap | None,
         suffix: str = "", diff_title: str = "", moves=None) -> bool:
    """render<suffix>.png/.txt, and diff<suffix>.png/.txt against `previous` when given.
    `moves` (a movement check result) hatches unreachable sectors and tints soft-locks.
    Returns whether the map changed (True when there's nothing to compare with)."""
    from dms import render

    d = info.build_dir(root)
    png = render.render(tm, d / f"render{suffix}.png", issues, title=f"{info.name}{suffix}",
                        unreachable=moves.unreachable if moves else (),
                        softlocks=moves.softlocks if moves else ())
    print(f"    wrote {png} (+ {png.with_suffix('.txt').name})")
    if previous is not None:
        diff_png = d / f"diff{suffix}.png"
        if render.render_diff(previous, tm, diff_png, title=diff_title or f"{info.name}{suffix}"):
            print(f"    wrote {diff_png} (+ {diff_png.with_suffix('.txt').name})")
        else:
            print("    no changes since the previous build")
            return False
    return True


def needs_build(info: MapInfo, root: Path) -> bool:
    out = info.wad(root)
    if not out.exists():
        return True
    sources = [info.folder / "map.toml", info.textmap, info.generator, info.folder / "overrides.toml",
               info.folder / "zscript.zs", info.folder / "textures.txt", info.folder / "animdefs.txt"]
    newest = max((p.stat().st_mtime for p in sources if p.exists()), default=0)
    return newest > out.stat().st_mtime


def read_edit_wad_textmap(info: MapInfo, root: Path) -> udmf.Textmap:
    """The map as the mapper last saved it in the editor (build/<map>/edit.wad)."""
    ew = info.edit_wad(root)
    if not ew.exists():
        raise BuildError(f"{ew} doesn't exist (open the map with `dms edit` first)")
    _, lumps = wad.read(ew)
    i = wad.find(lumps, "TEXTMAP")
    if i < 0:
        raise BuildError(f"{ew} has no TEXTMAP")
    return udmf.parse(lumps[i].data.decode("utf-8"))


